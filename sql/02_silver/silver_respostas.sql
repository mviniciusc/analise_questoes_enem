-- script da camada silver da tabela de respostas
CREATE OR REPLACE TABLE silver_respostas AS
	SELECT 
		CAST(NU_ANO AS INTEGER) AS ANO,
		CAST(TP_PRESENCA_CN AS INTEGER) AS PRESENTE_CN,
		CAST(TP_PRESENCA_CH AS INTEGER) AS PRESENTE_CH,
		CAST(TP_PRESENCA_LC AS INTEGER) AS PRESENTE_LC,
		CAST(TP_PRESENCA_MT AS INTEGER) AS PRESENTE_MT,
		CAST(CO_PROVA_CN AS INTEGER) AS CO_PROVA_CN,
		CAST(CO_PROVA_CH AS INTEGER) AS CO_PROVA_CH,
		CAST(CO_PROVA_LC AS INTEGER) AS CO_PROVA_LC,
		CAST(CO_PROVA_MT AS INTEGER) AS CO_PROVA_MT,
		CAST(REPLACE(NU_NOTA_CN,',','.') AS FLOAT) AS NOTA_CN,
		CAST(REPLACE(NU_NOTA_CH,',','.') AS FLOAT) AS NOTA_CH,
		CAST(REPLACE(NU_NOTA_LC,',','.') AS FLOAT) AS NOTA_LC,
		CAST(REPLACE(NU_NOTA_MT,',','.') AS FLOAT) AS NOTA_MT,
		TRIM(TX_RESPOSTAS_CN) AS RESPOSTAS_CN,
		TRIM(TX_RESPOSTAS_CH) AS RESPOSTAS_CH,
		REPLACE(TRIM(TX_RESPOSTAS_LC),'99999','') AS RESPOSTAS_LC, -- Replace necessário pra tirar os 99999 das respostas de lingua estrangeira
		TRIM(TX_RESPOSTAS_MT) AS RESPOSTAS_MT,
		CAST(TP_LINGUA AS INTEGER) AS TP_LINGUA,
		TRIM(TX_GABARITO_CN) AS GABARITO_CN,
		TRIM(TX_GABARITO_CH) AS GABARITO_CH,
		TRIM(TX_GABARITO_LC) AS GABARITO_LC,
		CASE -- Case necessário para remover as respostas da prova de lingua estrangeira que o candidato não escolheu
			WHEN TP_LINGUA = 0 THEN SUBSTRING(TX_GABARITO_LC,1,5) || SUBSTRING(TX_GABARITO_LC,11,50)
			WHEN TP_LINGUA = 1 THEN SUBSTRING(TX_GABARITO_LC,6,50)
		END AS GABARITO_LC,
		TRIM(TX_GABARITO_MT) AS GABARITO_MT,
		CAST(TP_STATUS_REDACAO AS INTEGER) AS STATUS_REDACAO,
		CAST(NU_NOTA_COMP1 AS INTEGER) AS REDACAO_COMP1,
		CAST(NU_NOTA_COMP2 AS INTEGER) AS REDACAO_COMP2,
		CAST(NU_NOTA_COMP3 AS INTEGER) AS REDACAO_COMP3,
		CAST(NU_NOTA_COMP4 AS INTEGER) AS REDACAO_COMP4,
		CAST(NU_NOTA_COMP5 AS INTEGER) AS REDACAO_COMP5,
		CAST(NU_NOTA_REDACAO AS INTEGER) AS REDACAO_NOTA,
	FROM enem.main.bronze_respostas
	WHERE 
		-- Filtro pra eliminar quem faltou nos dois dias
		TP_PRESENCA_CN <> '0'
		OR TP_PRESENCA_CH <> '0'
		OR TP_PRESENCA_LC <> '0'
		OR TP_PRESENCA_MT <> '0'




